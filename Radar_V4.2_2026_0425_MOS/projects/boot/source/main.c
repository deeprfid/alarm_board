/**
 *******************************************************************************
 * @file  main.c
 * @brief HC32F460 报警板 Bootloader 入口 —— 刻意保持最小
 *
 * 为什么这么小：
 *   1) 本板没有可接 printf 的调试口（唯一串口是 RS485 业务口），一切诊断走 LED 编码；
 *   2) 【关键】原版(扫描板 boot_iap)开头会配 8MHz 晶振 + PLL 200MHz，其中有
 *      while (SET != CLK_GetStableStatus(CLK_STB_FLAG_PLL)) ; 死等 PLL 锁定 ——
 *      雷达板若无该晶振或起振参数不同，Boot 就【死在这一行】：不跳转、不点灯、
 *      没有任何现象，与「烧完不启动」完全吻合。既然不需要串口，就不该配时钟。
 *   3) 不碰 GPIO/USART/定时器 —— 把外设状态原样留给 App（App 自己会全量初始化）。
 *
 * 本 Boot 只做三件事：点灯指示 -> 读标志 -> 判定并跳转。
 *******************************************************************************
 */
#include "hc32_ll.h"
#include "boot_ota.h"

#define BOOT_PERIPH_WE_SEL   (LL_PERIPH_GPIO | LL_PERIPH_FCG | LL_PERIPH_PWC_CLK_RMU | \
                              LL_PERIPH_EFM | LL_PERIPH_SRAM)

int32_t main(void)
{
    /* 只解外设寄存器写保护（GPIO/EFM 要用），不做任何时钟/串口配置 */
    LL_PERIPH_WE(BOOT_PERIPH_WE_SEL);

    /* 引导（不返回）：LED 指示 + 读标志 + 校验槽 + 跳转 / 停在 Boot */
    BOOT_OTA_Run();

    for (;;) {
        ;   /* 不应到达 */
    }
}

